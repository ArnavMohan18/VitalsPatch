/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  HAL_Init();

  SystemClock_Config();

  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_I2S3_Init();
  MX_SPI1_Init();
  MX_USB_HOST_Init();
  MX_USART2_UART_Init();

  /* USER CODE BEGIN 2 */
  HAL_GPIO_WritePin(LD4_GPIO_Port, LD4_Pin, GPIO_PIN_RESET);

  uart_send_string("\r\nSTM32 VitalsPatch receiver started\r\n");
  uart_send_string("Waiting for VP1 packets over USART2...\r\n");
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    MX_USB_HOST_Process();

    /*
     * Non-blocking-ish receive:
     * Waits up to 10 ms for one byte.
     * This keeps USB host process from getting stuck forever.
     */
    if (HAL_UART_Receive(&huart2, &rx_byte, 1, 10) == HAL_OK)
    {
      if (rx_byte == '\n')
      {
        rx_line[rx_index] = '\0';
        process_received_line(rx_line);
        rx_index = 0;
      }
      else if (rx_byte != '\r')
      {
        if (rx_index < RX_LINE_SIZE - 1)
        {
          rx_line[rx_index++] = rx_byte;
        }
        else
        {
          rx_index = 0;
          uart_send_string("RX BUFFER OVERFLOW\r\n");
        }
      }
    }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

